Aes128Cfb::Aes128Cfb(const QByteArray &key)
{
    if (key.size() != 16)
        return;

    std::memcpy(m_roundKeys.data(), key.constData(), 16);
    for (int i = 16, round = 0; i < 176; i += 4) {
        unsigned char t[4] = {m_roundKeys[i - 4], m_roundKeys[i - 3],
                              m_roundKeys[i - 2], m_roundKeys[i - 1]};
        if (i % 16 == 0) {
            const unsigned char first = t[0];
            t[0] = static_cast<unsigned char>(kSbox[t[1]] ^ kRcon[round++]);
            t[1] = kSbox[t[2]];
            t[2] = kSbox[t[3]];
            t[3] = kSbox[first];
        }
        for (int j = 0; j < 4; ++j)
            m_roundKeys[i + j] = m_roundKeys[i - 16 + j] ^ t[j];
    }
    m_valid = true;
}

void Aes128Cfb::encryptBlock(const unsigned char in[16], unsigned char out[16]) const
{
    unsigned char s[16];
    for (int i = 0; i < 16; ++i)
        s[i] = in[i] ^ m_roundKeys[i];

    for (int round = 1; round <= 10; ++round) {
        // SubBytes and ShiftRows together: the state is column-major, so row r
        // moves left by r columns.
        unsigned char t[16];
        for (int c = 0; c < 4; ++c)
            for (int r = 0; r < 4; ++r)
                t[c * 4 + r] = kSbox[s[((c + r) % 4) * 4 + r]];

        if (round < 10) {
            for (int c = 0; c < 4; ++c) {
                unsigned char *col = t + c * 4;
                const unsigned char all = col[0] ^ col[1] ^ col[2] ^ col[3];
                const unsigned char first = col[0];
                col[0] ^= all ^ xtime(col[0] ^ col[1]);
                col[1] ^= all ^ xtime(col[1] ^ col[2]);
                col[2] ^= all ^ xtime(col[2] ^ col[3]);
                col[3] ^= all ^ xtime(col[3] ^ first);
            }
        }

        for (int i = 0; i < 16; ++i)
            s[i] = t[i] ^ m_roundKeys[round * 16 + i];
    }
    std::memcpy(out, s, 16);
}

QByteArray Aes128Cfb::run(const QByteArray &data, const QByteArray &iv,
                          bool encrypting) const
{
    if (!m_valid || iv.size() != 16)
        return {};

    unsigned char feedback[16];
    std::memcpy(feedback, iv.constData(), 16);

    QByteArray out(data.size(), Qt::Uninitialized);
    const auto *in = reinterpret_cast<const unsigned char *>(data.constData());
    auto *dst = reinterpret_cast<unsigned char *>(out.data());

    for (qsizetype pos = 0; pos < data.size(); pos += 16) {
        unsigned char stream[16];
        encryptBlock(feedback, stream);
        const qsizetype n = qMin<qsizetype>(16, data.size() - pos);
        for (qsizetype i = 0; i < n; ++i) {
            dst[pos + i] = in[pos + i] ^ stream[i];
            // The next keystream block comes from the ciphertext, whichever
            // direction this is. A short final block has no successor.
            feedback[i] = encrypting ? dst[pos + i] : in[pos + i];
        }
    }
    return out;
}

QByteArray Aes128Cfb::encrypt(const QByteArray &data, const QByteArray &iv) const
{
    return run(data, iv, true);
}

QByteArray Aes128Cfb::decrypt(const QByteArray &data, const QByteArray &iv) const
{
    return run(data, iv, false);
}

