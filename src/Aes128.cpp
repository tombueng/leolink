constexpr unsigned char kRcon[10] = {0x01, 0x02, 0x04, 0x08, 0x10,
                                     0x20, 0x40, 0x80, 0x1b, 0x36};

unsigned char xtime(unsigned char x)
{
    return static_cast<unsigned char>((x << 1) ^ ((x & 0x80) ? 0x1b : 0x00));
}

